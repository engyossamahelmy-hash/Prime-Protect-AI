def _hash(pw, salt):
    return hashlib.pbkdf2_hmac("sha256", pw.encode(), bytes.fromhex(salt), 200_000).hex()


def add_user(name, pw, max_mb=MAX_MB, daily=30):
    salt = os.urandom(16).hex()
    c = _db()
    c.execute("INSERT OR REPLACE INTO users VALUES(?,?,?,?,?)", (name, salt, _hash(pw, salt), int(max_mb), int(daily)))
    c.commit()
    c.close()


def check_user(name, pw):
    c = _db()
    r = c.execute("SELECT * FROM users WHERE name=?", (name,)).fetchone()
    c.close()
    if r and hmac.compare_digest(_hash(pw, r["salt"]), r["pw"]):
        return {"name": r["name"], "max_mb": r["max_mb"], "daily": r["daily"]}
    return None


