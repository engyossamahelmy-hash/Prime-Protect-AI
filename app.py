def ev_fit(X, y, l2=1.0, lr=0.2, it=3000):
    """انحدار لوجستي موزون الفئات بـ numpy."""
    X = X.astype(float)
    fill = X.median().fillna(0)
    Xf = X.fillna(fill)
    mu, sd = Xf.mean(), Xf.std().replace(0, 1).fillna(1)
    Z, y = ((Xf - mu) / sd).values, np.asarray(y, float)
    sw = np.where(y == 1, 0.5 / max(y.mean(), 1e-6), 0.5 / max(1 - y.mean(), 1e-6))
    w, b = np.zeros(Z.shape[1]), 0.0
    for _ in range(it):
        p = 1 / (1 + np.exp(-(Z @ w + b)))
        g = (p - y) * sw
        w -= lr * (Z.T @ g / len(y) + l2 * w / len(y))
        b -= lr * g.mean()
    return {"features": list(X.columns), "fill": {k: float(v) for k, v in fill.items()},
            "mean": [float(v) for v in mu], "std": [float(v) for v in sd], "w": [float(v) for v in w], "b": float(b)}


def ev_predict(m, X):
    Xf = X[m["features"]].astype(float).fillna(pd.Series(m["fill"]))
    Z = (Xf.values - np.array(m["mean"])) / np.array(m["std"])
    return 1 / (1 + np.exp(-(Z @ np.array(m["w"]) + m["b"])))


def ev_auc(y, s):
    y, s = np.asarray(y), np.asarray(s, float)
    n1, n0 = int(y.sum()), int(len(y) - y.sum())
    if not n1 or not n0:
        return float("nan")
    r = pd.Series(s).rank().values
    return float((r[y == 1].sum() - n1 * (n1 + 1) / 2) / (n1 * n0))


def ev_thr(y, s):
    y, s = np.asarray(y), np.asarray(s)
    best = (-9, 0.5)
    for t in np.unique(s):
        pr = s >= t
        j = pr[y == 1].mean() - pr[y == 0].mean()
        if j > best[0]:
            best = (j, float(t))
    return best[1]


def ev_conf(y, s, t):
    y, pr = np.asarray(y), (np.asarray(s) >= t).astype(int)
    tp, fp = int(((pr == 1) & (y == 1)).sum()), int(((pr == 1) & (y == 0)).sum())
    tn, fn = int(((pr == 0) & (y == 0)).sum()), int(((pr == 0) & (y == 1)).sum())
    prec, rec = tp / max(tp + fp, 1), tp / max(tp + fn, 1)
    return dict(tp=tp, fp=fp, tn=tn, fn=fn, acc=(tp + tn) / max(len(y), 1), prec=prec, rec=rec,
                f1=2 * prec * rec / max(prec + rec, 1e-9))


def ev_roc(y, s):
    y, s = np.asarray(y), np.asarray(s)
    ts = np.r_[np.inf, np.sort(np.unique(s))[::-1]]
    return [(float((s[y == 0] >= t).mean()), float((s[y == 1] >= t).mean())) for t in ts]


def ev_cv(df, feats, scheme, seed=0):
    """loto: اترك أداة توليد كاملة للاختبار (اختبار التعميم). kfold: 5 طيّات.
    التدريب على النسخ الأصلية فقط؛ الاختبار يشمل كل نسخ الملف المحجوز (الأصل والمضغوط)."""
    srcs = df[df.variant == "orig"][["src", "label", "tool"]].drop_duplicates()
    rng, fold = np.random.RandomState(seed), {}
    if scheme == "loto":
        tools = sorted(srcs[srcs.label == 1].tool.unique())
        if len(tools) < 2:
            return None
        for i, t in enumerate(tools):
            fold.update({s: i for s in srcs[srcs.tool == t].src})
        reals = srcs[srcs.label == 0].src.values
        for i, s in enumerate(reals[rng.permutation(len(reals))]):
            fold[s] = i % len(tools)
        k = len(tools)
    else:
        k = 5
        for lab in (0, 1):
            ss = srcs[srcs.label == lab].src.values
            for i, s in enumerate(ss[rng.permutation(len(ss))]):
                fold[s] = i % k
    d = df.copy()
    d["fold"] = d.src.map(fold)
    out = []
    for f in range(k):
        tr, te = d[(d.fold != f) & (d.variant == "orig")], d[d.fold == f]
        if tr.label.nunique() < 2 or te.empty:
            continue
        te = te.copy()
        te["p"] = ev_predict(ev_fit(tr[feats], tr.label.values), te)
        out.append(te)
    return pd.concat(out) if out else None


