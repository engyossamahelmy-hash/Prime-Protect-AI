@st.cache_resource
def cascades():
    if cv2 is None or not hasattr(cv2, "CascadeClassifier"):
        return None, None
    try:
        base = cv2.data.haarcascades
        fc = cv2.CascadeClassifier(base + "haarcascade_frontalface_default.xml")
        ec = cv2.CascadeClassifier(base + "haarcascade_eye.xml")
        return (fc, ec) if not fc.empty() and not ec.empty() else (None, None)
    except Exception:
        return None, None


def hf_ratio(g):
    h, w = g.shape
    s = min(h, w, 256)
    y0, x0 = (h - s) // 2, (w - s) // 2
    c = g[y0:y0 + s, x0:x0 + s].astype(np.float32)
    c -= c.mean()
    c *= np.outer(np.hanning(s), np.hanning(s)).astype(np.float32)
    f = np.abs(np.fft.fftshift(np.fft.fft2(c))) ** 2
    yy, xx = np.ogrid[:s, :s]
    r = np.hypot(yy - s / 2, xx - s / 2) / (s / 2)
    return float(f[r > 0.5].sum() / (f.sum() + 1e-9))


def noise_level(g):
    gf = g.astype(np.float32)
    return float((gf - cv2.GaussianBlur(gf, (0, 0), 1.2)).std())


def jpeg_bytes(frame, max_side=640, q=82):
    h, w = frame.shape[:2]
    k = max_side / max(h, w)
    if k < 1:
        frame = cv2.resize(frame, (int(w * k), int(h * k)))
    ok, enc = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, q])
    return enc.tobytes() if ok else b""


def ela_map(bgr, q=90):
    """خريطة تفاوت الضغط: فرق الإطار عن نسخته المعاد ضغطها."""
    ok, enc = cv2.imencode(".jpg", bgr, [cv2.IMWRITE_JPEG_QUALITY, q])
    dec = cv2.imdecode(enc, 1)
    return cv2.absdiff(bgr, dec).astype(np.float32).mean(axis=2)


def ela_var(d, bs=32):
    h, w = d.shape
    h2, w2 = h // bs * bs, w // bs * bs
    if h2 < bs * 3 or w2 < bs * 3:
        return 0.0
    b = d[:h2, :w2].reshape(h2 // bs, bs, w2 // bs, bs).mean(axis=(1, 3))
    return float(b.std() / (b.mean() + 1e-6))


def ela_heat(d):
    u8 = np.clip(d / max(float(d.max()), 1e-6) * 255, 0, 255).astype(np.uint8)
    return cv2.applyColorMap(u8, cv2.COLORMAP_INFERNO)


def face_metrics(g):
    """تباين حدة الوجه مقابل الإطار المحيط به: الدمج الرديء يخلّ بهذه النسبة."""
    fc, _ = cascades()
    if fc is None:
        return None
    faces = fc.detectMultiScale(g, 1.2, 5, minSize=(60, 60))
    if len(faces) == 0:
        return None
    x, y, w, h = max(faces, key=lambda f: f[2] * f[3])
    H, W = g.shape
    lap = cv2.Laplacian(g, cv2.CV_32F)
    inner = lap[y + int(.2 * h):y + int(.8 * h), x + int(.2 * w):x + int(.8 * w)]
    ex, ey = int(.25 * w), int(.25 * h)
    x0, y0, x1, y1 = max(0, x - ex), max(0, y - ey), min(W, x + w + ex), min(H, y + h + ey)
    box = lap[y0:y1, x0:x1]
    mask = np.ones(box.shape, bool)
    mask[y - y0:y - y0 + h, x - x0:x - x0 + w] = False
    if inner.size < 50 or mask.sum() < 50:
        return None
    return {"ratio": float((inner.var() + 1) / (box[mask].var() + 1))}


def blink_scan(cap, fps, start):
    """تقدير تقريبي لمعدل الرمش بكاشف هار: العين المفتوحة تُكتشف والمغلقة لا."""
    fc, ec = cascades()
    if fc is None or ec is None:
        return {}
    cap.set(cv2.CAP_PROP_POS_FRAMES, int(start))
    total = int(min(8 * (fps or 25), 300))
    flags = []
    for _ in range(total):
        ok, fr = cap.read()
        if not ok:
            break
        s = min(1.0, 480 / max(fr.shape[:2]))
        g = cv2.cvtColor(cv2.resize(fr, None, fx=s, fy=s) if s < 1 else fr, cv2.COLOR_BGR2GRAY)
        faces = fc.detectMultiScale(g, 1.2, 5, minSize=(60, 60))
        if len(faces) == 0:
            flags.append(None)
            continue
        x, y, w, h = max(faces, key=lambda f: f[2] * f[3])
        roi = g[y:y + int(h * .55), x:x + w]
        eyes = ec.detectMultiScale(roi, 1.1, 6, minSize=(max(12, w // 10),) * 2)
        flags.append(len(eyes) >= 1)
    blinks, run, seen = 0, 0, False
    for f in flags:
        if f is None:
            run = 0
        elif f:
            if seen and 1 <= run <= 8:
                blinks += 1
            run, seen = 0, True
        else:
            run += 1
    ff = [f for f in flags if f is not None]
    secs = len(ff) / fps if fps else 0
    return {"blinks": blinks, "secs": secs, "rate": (blinks / secs * 60) if secs else 0,
            "open_ratio": (sum(ff) / len(ff)) if ff else 0}


def sample_scores(S):
    out = []
    n = min(len(S[k]) for k in ("t", "noise", "motion", "warp", "ela", "face"))
    for i in range(n):
        s = 35 * clip01((1.6 - S["noise"][i]) / 1.6)
        if S["motion"][i] > 0.2:
            s += 35 * clip01((S["warp"][i] - 5) / 8)
        s += 15 * clip01((S["ela"][i] - 0.8) / 1.2)
        fr = S["face"][i]
        if fr:
            s += 15 * clip01((abs(math.log(fr)) - 0.7) / 1.5)
        out.append(round(min(100.0, s), 1))
    return out


