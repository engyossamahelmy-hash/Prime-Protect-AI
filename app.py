def render_batch(user, depth, use_faces, use_audio):
    st.markdown('<div class="sec">فحص دفعي</div>', unsafe_allow_html=True)
    files = st.file_uploader("ارفع عدة فيديوهات", type=VID_EXT, accept_multiple_files=True, key="batch_up")
    if not files or not st.button("🔍 افحص الدفعة", use_container_width=True):
        return
    anchors = {"سريع": 10, "متوسط": 18, "عميق": 32}[depth]
    rows, bar = [], st.progress(0.0)
    for i, f in enumerate(files):
        d = f.getvalue()
        if len(d) > user["max_mb"] * 1e6:
            rows.append({"الملف": f.name, "المؤشر": "-", "الحكم": "أكبر من الحد المسموح"})
        elif scans_today(user["name"]) >= user["daily"]:
            rows.append({"الملف": f.name, "المؤشر": "-", "الحكم": "تجاوز الحد اليومي"})
        else:
            r = analyze(d, f.name, anchors, use_faces, use_audio, cb=lambda *_: None)
            s = hashlib.sha256(d).hexdigest().upper()
            r["now"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            r["sig"] = sign(s, r["score"], r["now"])
            lv, lb, _ = verdict_from(r["score"], r["explicit"])
            save_scan(user["name"], f.name, s, f"PS-{s[:8]}", r["now"], r, lv, lb)
            rows.append({"الملف": f.name, "المؤشر": r["score"], "الحكم": lb,
                         "احتمال النموذج": None if r["p_model"] is None else f"{r['p_model'] * 100:.0f}%",
                         "الكود": f"PS-{s[:8]}"})
        bar.progress((i + 1) / len(files))
    bar.empty()
