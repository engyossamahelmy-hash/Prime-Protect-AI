def analyze_audio(path, tts_marks):
    out = {"has": False, "ind": [], "metrics": {}, "pts": 0, "db": None, "spec": None, "explicit": False, "feat": {}}
    if tts_marks:
        out["explicit"] = True
        out["ind"].append(("bad", "قوي", f"عُثر داخل الملف على اسم أداة صوت اصطناعي: {', '.join(tts_marks)}."))
    ff = ffmpeg_path()
    if not ff:
        out["ind"].append(("info", "معلومة", "تحليل الصوت يحتاج ffmpeg. ثبّته (pip install imageio-ffmpeg) أو أضفه إلى PATH."))
        return out
    try:
        kw = {"creationflags": 0x08000000} if os.name == "nt" else {}
        r = subprocess.run([ff, "-v", "error", "-i", path, "-vn", "-ac", "1", "-ar", "44100", "-t", "60", "-f", "s16le", "-"],
                           capture_output=True, timeout=180, **kw)
        pcm = np.frombuffer(r.stdout, np.int16)
    except Exception as e:
        out["ind"].append(("warn", "تنبيه", f"تعذّر استخراج الصوت: {e}"))
        return out
    if len(pcm) < 22050:
        out["ind"].append(("info", "معلومة", "لا يحتوي الفيديو على مسار صوتي (أو أنه قصير جداً)."))
        return out

    out["has"] = True
    sr = 44100
    x = pcm.astype(np.float32) / 32768
    win = 882
    nf = len(x) // win
    fr = x[:nf * win].reshape(nf, win)
    db = 20 * np.log10(np.sqrt((fr ** 2).mean(1)) + 1e-9)
    peak, floor = float(np.percentile(db, 95)), float(np.percentile(db, 5))
    voiced = db > peak - 30
    dyn = float(db[voiced].std()) if voiced.sum() > 5 else 0.0
    dsil = float((np.abs(fr).max(1) <= 1.5 / 32768).mean())

    N = 2048
    nb = len(x) // N
    F = x[:nb * N].reshape(nb, N)
    e = 10 * np.log10((F ** 2).mean(1) + 1e-12)
    P = np.abs(np.fft.rfft(F * np.hanning(N), axis=1)) ** 2
    mask = e > e.max() - 35
    Pm = P[mask].mean(0) if mask.any() else P.mean(0)
    freqs = np.fft.rfftfreq(N, 1 / sr)
    sdb = 10 * np.log10(Pm / (Pm.max() + 1e-12) + 1e-12)
    idx = np.where(sdb > -70)[0]
    fcut = float(freqs[idx.max()]) if len(idx) else 0.0
    hf = float(Pm[freqs > 8000].sum() / (Pm.sum() + 1e-12))

    rep = 0.0
    edges = np.unique(np.geomspace(2, N // 2, 33).astype(int))
    bands = np.stack([np.log(P[:, a:b].sum(1) + 1e-9) for a, b in zip(edges[:-1], edges[1:])], axis=1)
    blocks, benergy = [], []
    for i in range(0, nb - 4, 2):
        v = bands[i:i + 4].reshape(-1)
        v = v - v.mean()
        blocks.append(v / (np.linalg.norm(v) + 1e-9))
        benergy.append(e[i:i + 4].mean())
    if len(blocks) > 30:
        V = np.array(blocks)
        keep = np.array(benergy) > e.max() - 25
        V = V[keep]
        if len(V) > 30:
            sim = V @ V.T
            ii = np.arange(len(V))
            sim[np.abs(ii[:, None] - ii[None, :]) < 8] = -1
            rep = float((sim.max(1) > 0.995).mean())

    out["metrics"] = {"مدة الصوت": f"{len(x) / sr:.1f} ث", "حد الترددات": f"{fcut / 1000:.1f} kHz",
                      "أرضية الضجيج": f"{floor:.0f} dB", "تنوع الشدة": f"{dyn:.1f} dB",
                      "صمت رقمي تام": f"{dsil * 100:.0f}%", "تكرار المقاطع": f"{rep * 100:.0f}%"}
    out["feat"] = {"a_dsil": dsil, "a_hf": hf, "a_rep": rep, "a_dyn": dyn}
    pts = 0
    if dsil > 0.1:
        pts += 6
        out["ind"].append(("warn", "ضعيف", "فترات صمت رقمي تام بلا أي ضجيج غرفة. يحدث في الكلام المركّب، وأيضاً في الصوت المنظَّف أو المقصوص."))
    if hf < 1e-6:
        pts += 5
        out["ind"].append(("warn", "ضعيف", f"الصوت محدود النطاق عند نحو {fcut / 1000:.1f} kHz. هذا شائع في مخرجات TTS، وفي المكالمات والميكروفونات الضعيفة أيضاً."))
    if rep > 0.1:
        pts += 6
        out["ind"].append(("warn", "ضعيف", f"{rep * 100:.0f}% من مقاطع الكلام متطابقة تقريباً مع مقاطع أخرى، والكلام البشري الطبيعي لا يكرر نفسه بهذا الشكل."))
    if not pts and not out["ind"]:
        out["ind"].append(("ok", "يطمئن", "لم تظهر في الصوت مؤشرات واضحة على التركيب: يوجد ضجيج غرفة وتنوع طبيعي في الشدة."))
    out["pts"] = pts
    per_s = nf // 50
    out["db"] = pd.DataFrame({"شدة الصوت (dB)": [float(db[i * 50:(i + 1) * 50].mean()) for i in range(per_s)]})
    sel = (freqs <= 20000)
    out["spec"] = pd.DataFrame({"المستوى (dB)": sdb[sel][::3]}, index=np.round(freqs[sel][::3] / 1000, 2))
    return out


