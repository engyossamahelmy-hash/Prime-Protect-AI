def top_ranges(res, k=3, min_score=25):
    ts, sc = res["series"]["t"], res["sample_scores"]
    if len(ts) < 2:
        return []
    half = (ts[1] - ts[0]) / 2
    out = []
    for i in np.argsort(sc)[::-1][:k]:
        if sc[i] >= min_score:
            out.append((max(0, ts[i] - half), min(res["dur"], ts[i] + half), sc[i]))
    return sorted(out)


