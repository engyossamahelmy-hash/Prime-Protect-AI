def make_pdf(res, name, sha, code, now, ai_text):
    if not PDF_OK:
        return None, "لتصدير PDF ثبّت: pip install reportlab arabic-reshaper python-bidi"
    font = pdf_font()
    if not font:
        return None, "لم أجد خطاً عربياً. ضع ملف خط (مثل tahoma.ttf) بجانب primesave.py وسمّه font.ttf"

    buf = io.BytesIO()
    c = rl_canvas.Canvas(buf, pagesize=A4)
    W, H = A4
    M = 42
    GOLD, DARK, GREY = colors.HexColor("#B8923F"), colors.HexColor("#15171a"), colors.HexColor("#555555")
    LV = {"low": colors.HexColor("#2E9E75"), "mid": colors.HexColor("#D59A1E"), "high": colors.HexColor("#D23B40")}
    pos = {"y": H - 112, "p": 1}

    def ar(t):
        return get_display(arabic_reshaper.reshape(str(t)))

    def footer():
        c.setStrokeColor(colors.HexColor("#CCCCCC"))
        c.line(M, M - 6, W - M, M - 6)
        c.setFont(font, 8)
        c.setFillColor(GREY)
        c.drawRightString(W - M, M - 19, ar("فحص أولي لا يغني عن الخبير الجنائي الرقمي"))
        c.drawString(M, M - 19, f"Prime Save AI  |  {pos['p']}")

    def newpage():
        footer()
        c.showPage()
        pos["p"] += 1
        pos["y"] = H - M

    def need(h):
        if pos["y"] - h < M + 8:
            newpage()

    def wrap(text, size, maxw):
        lines, cur = [], ""
        for w_ in str(text).split(" "):
            t = (cur + " " + w_).strip()
            if pdfmetrics.stringWidth(ar(t), font, size) <= maxw:
                cur = t
            else:
                lines.append(cur)
                cur = w_
        lines.append(cur)
        return lines

    def para(text, size=10, color=colors.black, indent=0):
        for ln in wrap(text, size, W - 2 * M - indent):
            need(size + 6)
            c.setFont(font, size)
            c.setFillColor(color)
            c.drawRightString(W - M - indent, pos["y"], ar(ln))
            pos["y"] -= size + 6

    def section(title):
        need(40)
        pos["y"] -= 8
        c.setFillColor(GOLD)
        c.rect(W - M - 4, pos["y"] - 3, 4, 16, fill=1, stroke=0)
        c.setFont(font, 13)
        c.drawRightString(W - M - 12, pos["y"], ar(title))
        pos["y"] -= 22

    def table(rows):
        for i, (k, v) in enumerate(rows):
            need(20)
            if i % 2 == 0:
                c.setFillColor(colors.HexColor("#F3F1EA"))
                c.rect(M, pos["y"] - 5, W - 2 * M, 18, fill=1, stroke=0)
            c.setFillColor(colors.black)
            c.setFont(font, 9.5)
            c.drawRightString(W - M - 6, pos["y"], ar(k))
            c.drawString(M + 6, pos["y"], ar(v) if any("\u0600" <= ch <= "\u06ff" for ch in str(v)) else str(v))
            pos["y"] -= 18
        pos["y"] -= 4

    # الترويسة والشعار
    c.setFillColor(DARK)
    c.rect(0, H - 92, W, 92, fill=1, stroke=0)
    sx, sy = W - M - 22, H - 64
    p = c.beginPath()
    p.moveTo(sx - 20, sy + 30)
    p.lineTo(sx + 20, sy + 30)
    p.lineTo(sx + 20, sy + 8)
    p.curveTo(sx + 20, sy - 8, sx + 6, sy - 14, sx, sy - 18)
    p.curveTo(sx - 6, sy - 14, sx - 20, sy - 8, sx - 20, sy + 8)
    p.close()
    c.setFillColor(GOLD)
    c.drawPath(p, fill=1, stroke=0)
    c.setFillColor(DARK)
    t = c.beginPath()
    t.moveTo(sx - 5, sy + 20)
    t.lineTo(sx - 5, sy + 2)
    t.lineTo(sx + 9, sy + 11)
    t.close()
    c.drawPath(t, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont(font, 20)
    c.drawRightString(sx - 32, H - 50, "Prime Save AI")
    c.setFont(font, 11)
    c.setFillColor(colors.HexColor("#D4B26A"))
    c.drawRightString(sx - 32, H - 70, ar("تقرير فحص فيديو رقمي"))

    level, label, sub = verdict_from(res["score"], res["explicit"])
    section("بيانات الملف")
    table([("اسم الملف", name), ("وقت الفحص", now), ("كود التحقق", code), ("توقيع التقرير", res.get("sig", ""))])
    para("SHA-256:", 9, GREY)
    for i in (0, 32):
        need(14)
        c.setFont("Courier", 9)
        c.setFillColor(colors.black)
        c.drawRightString(W - M, pos["y"], sha[i:i + 32])
        pos["y"] -= 13
    png = qr_png(f"PS|{sha}|{res['score']}|{now}|{res.get('sig', '')}")
    if png:
        need(98)
        c.drawImage(ImageReader(io.BytesIO(png)), M, pos["y"] - 90, 90, 90)
        c.setFont(font, 8)
        c.setFillColor(GREY)
        c.drawString(M + 100, pos["y"] - 40, "Scan to verify: SHA-256 | score | time | HMAC")
        pos["y"] -= 98

    section("النتيجة")
    need(70)
    c.setFillColor(LV[level])
    c.roundRect(M, pos["y"] - 50, W - 2 * M, 58, 8, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont(font, 30)
    c.drawString(M + 18, pos["y"] - 30, f"{res['score']}/100")
    c.setFont(font, 13)
    c.drawRightString(W - M - 16, pos["y"] - 14, ar(label))
    c.setFont(font, 9)
    c.drawRightString(W - M - 16, pos["y"] - 34, ar("مؤشر اشتباه تقني وليس حكماً قاطعاً"))
    pos["y"] -= 70

    section("جدول القياسات")
    table(list(all_metrics(res).items()))

    section("ما رصده الفحص")
    order = {"bad": 0, "warn": 1, "info": 2, "ok": 3}
    for cls, w_, txt in sorted(res["ind"], key=lambda x: order[x[0]]):
        para(f"[{w_}] {txt}", 9.5, indent=0)

    if res["sample_scores"]:
        section("الخريطة الزمنية لمؤشر الاشتباه")
        ts, sc = res["series"]["t"], res["sample_scores"]
        h = 110
        need(h + 40)
        x0, x1, y1 = M + 22, W - M, pos["y"]
        y0 = y1 - h
        c.setStrokeColor(GREY)
        c.setLineWidth(.6)
        c.rect(x0, y0, x1 - x0, h)
        c.setDash(3, 3)
        c.setStrokeColor(LV["high"])
        c.line(x0, y0 + h * .4, x1, y0 + h * .4)
        c.setDash()
        tmin, tmax = min(ts), max(ts)
        px = lambda tt: x0 + (tt - tmin) / (tmax - tmin + 1e-9) * (x1 - x0)
        py = lambda v: y0 + v / 100 * h
        path = c.beginPath()
        path.moveTo(px(ts[0]), py(sc[0]))
        for tt, v in zip(ts[1:], sc[1:]):
            path.lineTo(px(tt), py(v))
        c.setStrokeColor(GOLD)
        c.setLineWidth(1.6)
        c.drawPath(path, stroke=1, fill=0)
        c.setFillColor(GOLD)
        for tt, v in zip(ts, sc):
            c.circle(px(tt), py(v), 2.2, fill=1, stroke=0)
        c.setFont(font, 7)
        c.setFillColor(GREY)
        c.drawString(x0, y0 - 10, fmt_t(tmin))
        c.drawRightString(x1, y0 - 10, fmt_t(tmax))
        c.drawRightString(x0 - 3, y0 + h - 5, "100")
        c.drawRightString(x0 - 3, y0, "0")
        pos["y"] = y0 - 24
        for a, b, s in top_ranges(res):
            para(f"الفترة {fmt_t(a)} إلى {fmt_t(b)}: مؤشر الاشتباه {s:.0f}", 9.5)

    if res["frames"]:
        section("الإطارات المفحوصة")
        pick = res["frames"][::max(1, len(res["frames"]) // 9)][:9]
        iw = (W - 2 * M - 20) / 3
        ih = iw * 0.62
        for i in range(0, len(pick), 3):
            need(ih + 26)
            for j, (tt, b) in enumerate(pick[i:i + 3]):
                x = W - M - (j + 1) * iw - j * 10
                try:
                    c.drawImage(ImageReader(io.BytesIO(b)), x, pos["y"] - ih, iw, ih, preserveAspectRatio=True, anchor="c")
                except Exception:
                    pass
                c.setFont(font, 8)
                c.setFillColor(GREY)
                c.drawCentredString(x + iw / 2, pos["y"] - ih - 10, fmt_t(tt))
            pos["y"] -= ih + 22

    if ai_text:
        section("قراءة الذكاء الاصطناعي")
        for line in ai_text.replace("*", "").replace("#", "").replace("`", "").split("\n"):
            if line.strip():
                para(line.strip(), 9.5)

    need(40)
    pos["y"] -= 6
    para("ملاحظة: هذا فحص أولي. غياب المؤشرات لا يثبت أصالة الفيديو، ووجودها لا يثبت توليده. للقضايا القانونية يلزم خبير جنائي رقمي.", 9, GREY)
    footer()
    c.save()
    return buf.getvalue(), None


