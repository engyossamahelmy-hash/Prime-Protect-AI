def predict(model, feat):
    if not model:
        return None
    fill = [model["fill"].get(k, 0.0) for k in model["features"]]
    x = np.array([feat.get(k) if feat.get(k) is not None else np.nan for k in model["features"]], float)
    x = np.where(np.isnan(x), fill, x)
    z = (x - np.array(model["mean"])) / np.array(model["std"])
    return float(1 / (1 + np.exp(-(z @ np.array(model["w"]) + model["b"]))))


