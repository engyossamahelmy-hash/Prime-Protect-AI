def container_check(data):
    """يقرأ صناديق MP4 الرئيسية: تعدد mdat، قوائم التحرير (elst)، أثر x264/ffmpeg، ترتيب moov."""
    feat = {"c_mdat": 0, "c_elst": 0, "c_x264": 0, "c_lavf": 0, "c_moov_last": 0}
    n, pos, boxes = len(data), 0, []
    while pos + 8 <= n and len(boxes) < 300:
        size, typ = struct.unpack(">I4s", data[pos:pos + 8])
        hdr = 8
        if size == 1 and pos + 16 <= n:
            size, hdr = struct.unpack(">Q", data[pos + 8:pos + 16])[0], 16
        elif size == 0:
            size = n - pos
        if size < hdr:
            break
        boxes.append(typ.decode("latin1"))
        pos += size
    if not boxes or boxes[0] != "ftyp":
        return {}, []          # ليست حاوية MP4/MOV (mkv/avi/webm): لا نقيّم

    ind = []
    feat["c_mdat"] = boxes.count("mdat")
    if "moov" in boxes and "mdat" in boxes:
        feat["c_moov_last"] = int(boxes.index("moov") > boxes.index("mdat"))
    blob = data[:2_000_000] + data[-2_000_000:]
    low = blob.lower()
    feat["c_lavf"] = int(b"lavf" in low or b"lavc" in low)
    feat["c_x264"] = int(b"x264 - core" in blob or b"x265" in low)
    elst_n, i = 0, -1
    while True:
        i = blob.find(b"elst", i + 1)
        if i < 0 or i + 12 > len(blob):
            break
        elst_n = max(elst_n, int.from_bytes(blob[i + 8:i + 12], "big"))
    feat["c_elst"] = elst_n

    if feat["c_mdat"] > 1:
        ind.append(("info", "معلومة", f"الملف يحوي {feat['c_mdat']} كتل بيانات (mdat): يحدث عند الدمج أو إعادة الكتابة بأدوات مونتاج."))
    if elst_n >= 2:
        ind.append(("info", "معلومة", f"قائمة تحرير بـ {elst_n} مقاطع: يدل على قصّ أو لصق داخل الحاوية."))
    if feat["c_x264"] or feat["c_lavf"]:
        ind.append(("info", "معلومة", "أثر ترميز x264/ffmpeg: الملف أُعيد تصديره بعد التصوير أو التوليد (شائع في كل منصات النشر، فلا يدل على التزييف وحده)."))
    return feat, ind


def _crop(fr, x0, y0, x1, y1):
    H, W = fr.shape[:2]
    return fr[max(0, y0):min(H, y1), max(0, x0):min(W, x1)]


def face_pass(cap, fc, fps, start, secs=10):
    """تمريرة واحدة: متوسط الأخضر في الجبهة + طاقة حركة الفم لكل إطار."""
    fps = fps or 25
    cap.set(cv2.CAP_PROP_POS_FRAMES, int(start))
    green, mouth, prev, box = [], [], None, None
    for i in range(int(min(secs * fps, 400))):
        ok, fr = cap.read()
        if not ok:
            break
        if box is None or i % 5 == 0:
            s = min(1.0, 480 / max(fr.shape[:2]))
            g = cv2.cvtColor(cv2.resize(fr, None, fx=s, fy=s) if s < 1 else fr, cv2.COLOR_BGR2GRAY)
            f = fc.detectMultiScale(g, 1.2, 5, minSize=(60, 60))
            if len(f):
                x, y, w, h = max(f, key=lambda a: a[2] * a[3])
                box = tuple(int(v / s) for v in (x, y, w, h))
        if box is None:
            green.append(np.nan)
            mouth.append(np.nan)
            prev = None
            continue
        x, y, w, h = box
        fh = _crop(fr, x + int(.25 * w), y + int(.1 * h), x + int(.75 * w), y + int(.3 * h))
        green.append(float(fh[..., 1].mean()) if fh.size else np.nan)
        mo = _crop(fr, x + int(.25 * w), y + int(.65 * h), x + int(.75 * w), y + int(.95 * h))
        if mo.size:
            m = cv2.resize(cv2.cvtColor(mo, cv2.COLOR_BGR2GRAY), (48, 24)).astype(np.float32)
            mouth.append(float(np.abs(m - prev).mean()) if prev is not None else np.nan)
            prev = m
        else:
            mouth.append(np.nan)
            prev = None
    return np.array(green), np.array(mouth), fps


def _fill(a):
    a = np.asarray(a, float).copy()
    ok = ~np.isnan(a)
    if ok.sum() < 10:
        return None
    a[~ok] = np.interp(np.flatnonzero(~ok), np.flatnonzero(ok), a[ok])
    return a


def rppg_from(green, fps):
    """نسبة قوة قمة النبض داخل النطاق 0.7–4 هرتز. تقريبي جداً ويتأثر بالضغط والإضاءة."""
    g = _fill(green)
    if g is None or len(g) < 4 * fps:
        return {}
    k = max(3, int(fps))
    g = g - np.convolve(g, np.ones(k) / k, mode="same")
    g = g * np.hanning(len(g))
    N = 2 ** int(math.ceil(math.log2(len(g) * 4)))
    P = np.abs(np.fft.rfft(g, N)) ** 2
    fr = np.fft.rfftfreq(N, 1 / fps)
    band = (fr >= 0.7) & (fr <= 4.0)
    if not band.any():
        return {}
    pk = float(fr[band][np.argmax(P[band])])
    near = band & (np.abs(fr - pk) < 0.15)
    return {"rppg_snr": float(P[near].sum() / (P[band].sum() + 1e-12)), "bpm": pk * 60}


def audio_env(ffmpeg, path, start_s, secs, fps, n):
    """غلاف شدة الصوت بمعدل إطارات الفيديو."""
    try:
        kw = {"creationflags": 0x08000000} if os.name == "nt" else {}
        r = subprocess.run([ffmpeg, "-v", "error", "-ss", f"{start_s:.2f}", "-t", f"{secs:.2f}", "-i", path,
                            "-vn", "-ac", "1", "-ar", "16000", "-f", "s16le", "-"], capture_output=True, timeout=120, **kw)
        x = np.frombuffer(r.stdout, np.int16).astype(np.float32) / 32768
    except Exception:
        return None
    spf = int(16000 / (fps or 25))
    m = min(n, len(x) // max(spf, 1))
    if m < 20:
        return None
    return np.sqrt((x[:m * spf].reshape(m, spf) ** 2).mean(1))


def lipsync_from(mouth, env):
    """أعلى ارتباط بين حركة الفم وشدة الصوت ضمن ±8 إطارات."""
    a = _fill(mouth)
    if a is None or env is None:
        return {}
    n = min(len(a), len(env))
    a, e = a[:n], np.asarray(env[:n], float)
    if n < 40 or a.std() < 1e-6 or e.std() < 1e-6:
        return {}
    a, e = (a - a.mean()) / a.std(), (e - e.mean()) / e.std()
    best = (-1.0, 0)
    for lag in range(-8, 9):
        x, y = (a[lag:], e[:n - lag]) if lag >= 0 else (a[:n + lag], e[-lag:])
        c = float((x * y).mean())
        if c > best[0]:
            best = (c, lag)
    return {"lip_corr": best[0], "lip_lag": best[1]}


_ONNX = {}


def onnx_deepfake(jpegs, path=None, size=224):
    """يشغّل نموذج ONNX لكشف التزييف محلياً (PS_ONNX=مسار النموذج). يرجع متوسط احتمال «مزيّف» أو None.
    تنبيه: التطبيع (mean/std) وترتيب المخرجات يختلفان من نموذج لنموذج؛ راجع بطاقة النموذج وعدّل هنا."""
    path = path or os.environ.get("PS_ONNX")
    if not path or not os.path.exists(path):
        return None
    try:
        import onnxruntime as ort
        sess = _ONNX.get(path) or ort.InferenceSession(path, providers=["CPUExecutionProvider"])
        _ONNX[path] = sess
        inp, ps = sess.get_inputs()[0].name, []
        for b in jpegs:
            im = cv2.cvtColor(cv2.imdecode(np.frombuffer(b, np.uint8), 1), cv2.COLOR_BGR2RGB)
            im = (cv2.resize(im, (size, size)).astype(np.float32) / 255 - 0.5) / 0.5
            o = np.asarray(sess.run(None, {inp: im.transpose(2, 0, 1)[None]})[0], float).reshape(-1)
            ps.append(float(1 / (1 + np.exp(-o[0]))) if o.size == 1 else float(np.exp(o[-1]) / np.exp(o).sum()))
        return float(np.mean(ps)) if ps else None
    except Exception:
        return None


