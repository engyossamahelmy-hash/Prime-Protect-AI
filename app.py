def sign(sha, score, now):
    """HMAC يثبت أن التقرير صدر من هذا الخادم وأن (البصمة، النتيجة، الوقت) لم تتغير. ليس ختماً زمنياً خارجياً."""
    key = os.environ.get("PS_SECRET", "dev-secret-change-me")
    return hmac.new(key.encode(), f"{sha}|{score}|{now}".encode(), hashlib.sha256).hexdigest().upper()[:24]


def verify(sha, score, now, sig):
    return hmac.compare_digest(sign(sha.strip().upper(), str(score).strip(), now.strip()), sig.strip().upper())


